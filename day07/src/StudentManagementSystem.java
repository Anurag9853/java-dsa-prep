public class StudentManagmentSystem {

    class Student {

        private String name;
        private int roll;
        private int marks;
        private int admissionYear;

        Student(String name, int roll, int marks, int admissionYear) {
            this.name = name;
            this.roll = roll;
            this.marks = marks;
            this.admissionYear = admissionYear;
        }
    }




}
